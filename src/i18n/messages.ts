export function formatMessage(template: string, vars?: Record<string, string | number>) {
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    vars[name] === undefined ? `{${name}}` : String(vars[name]),
  )
}

export function translate(lang: Lang, key: MessageKey, vars?: Record<string, string | number>) {
  return formatMessage(MESSAGES[lang][key] ?? MESSAGES.ru[key], vars)
}

export function cityLabel(city: string, lang: Lang) {
  const key = CITY_KEYS[city]
  return key ? translate(lang, key) : city
}

export function countryLabel(country: string, lang: Lang) {
  const key = COUNTRY_KEYS[country]
  return key ? translate(lang, key) : country
}

export function suggestionCopy(title: string, lang: Lang, fallback: { blurb: string; fact: string }) {
  const keys = SUGGEST_KEYS[title]
  if (!keys) return fallback
  return { blurb: translate(lang, keys.blurb), fact: translate(lang, keys.fact) }
}

